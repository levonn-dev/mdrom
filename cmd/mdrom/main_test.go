func TestInjectWritesHookCodeAndHeader(t *testing.T) {
	base := writeSynth(t, 0x100000)
	out := filepath.Join(t.TempDir(), "patched.md")
	code, stdout, stderr := exec("inject", "--base", base, "--elf", pocELF, "--out", out, "--size", "0x200000")
	if code != 0 {
		t.Fatalf("code %d stderr %q", code, stderr)
	}
	img := mustRead(t, out)
	if len(img) != 0x200000 {
		t.Fatalf("output is %d bytes", len(img))
	}
	if !bytes.Equal(img[0x300:0x306], []byte{0x4E, 0xB9, 0x00, 0x10, 0x00, 0x00}) {
		t.Errorf("hook bytes = %x", img[0x300:0x306])
	}
	if !bytes.Equal(img[0x100000:0x100004], []byte{0x30, 0x2F, 0x00, 0x06}) {
		t.Errorf("code bytes = %x", img[0x100000:0x100004])
	}
	if img[0x100010] != 0xFF {
		t.Errorf("padding after code = %#x, want 0xFF", img[0x100010])
	}
	if end := binary.BigEndian.Uint32(img[0x1A4:]); end != 0x1FFFFF {
		t.Errorf("ROM end = %#x", end)
	}
	if stored := binary.BigEndian.Uint16(img[0x18E:]); stored != rom.Checksum(img) {
		t.Errorf("checksum stored %#x computed %#x", stored, rom.Checksum(img))
	}
	for _, want := range []string{".hook_000300", "0x000300", ".text", "0x100000", "ROM_FREE", "rom end: 0x1FFFFF", "ROM_FREE unused: 1048560 of 1048576 bytes"} {
		if !strings.Contains(stdout, want) {
			t.Errorf("stdout lacks %q:\n%s", want, stdout)
		}
	}
}

