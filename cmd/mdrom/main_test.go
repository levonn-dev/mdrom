// writeSynth writes a synthetic image of the given size into a temp dir and returns its path.
func writeSynth(t *testing.T, size int) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "base.md")
	if err := os.WriteFile(path, testrom.Synth(size), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

// writeSynthWithGap writes a synthetic image with bytes 0x1000..0x1800 zeroed,
// an interior gap the tests can target with --interior, and returns its path.
func writeSynthWithGap(t *testing.T, size int) string {
	t.Helper()
	img := testrom.Synth(size)
	for i := 0x1000; i < 0x1800; i++ {
		img[i] = 0
	}
	path := filepath.Join(t.TempDir(), "gap.md")
	if err := os.WriteFile(path, img, 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

// mustRead reads path or fails the test.
func mustRead(t *testing.T, path string) []byte {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

// mustWrite writes data to path or fails the test.
func mustWrite(t *testing.T, path string, data []byte) {
	t.Helper()
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
}

// exec runs the CLI in-process and returns exit code, stdout, stderr.
func exec(args ...string) (int, string, string) {
	var out, errb bytes.Buffer
	code := run(args, &out, &errb)
	return code, out.String(), errb.String()
}

