func TestBPSCreateApplyRoundTrip(t *testing.T) {
	base := writeSynth(t, 0x100000)
	dir := t.TempDir()
	patched := filepath.Join(dir, "patched.md")
	if code, _, stderr := exec("inject", "--base", base, "--elf", pocELF, "--out", patched, "--size", "0x200000"); code != 0 {
		t.Fatalf("inject: %s", stderr)
	}
	patch := filepath.Join(dir, "patch.bps")
	code, stdout, stderr := exec("bps", "create", "--base", base, "--target", patched, "--out", patch)
	if code != 0 || !strings.Contains(stdout, "wrote "+patch) {
		t.Fatalf("create: code %d stdout %q stderr %q", code, stdout, stderr)
	}
	info, err := os.Stat(patch)
	if err != nil {
		t.Fatal(err)
	}
	if info.Size() > 256 {
		t.Errorf("patch is %d bytes; expected a tiny patch for a hook plus 16 bytes of code", info.Size())
	}
	applied := filepath.Join(dir, "applied.md")
	code, stdout, stderr = exec("bps", "apply", "--base", base, "--patch", patch, "--out", applied)
	if code != 0 {
		t.Fatalf("apply: code %d stderr %q", code, stderr)
	}
	want := mustRead(t, patched)
	got := mustRead(t, applied)
	if !bytes.Equal(got, want) {
		t.Fatal("applied image differs from the injected image")
	}
	if !strings.Contains(stdout, rom.SHA1Hex(want)) {
		t.Errorf("apply output lacks the SHA-1:\n%s", stdout)
	}
}

func TestBPSApplyRejectsWrongBase(t *testing.T) {
	base := writeSynth(t, 0x100000)
	other := writeSynth(t, 0x100000)
	img := mustRead(t, other)
	img[0x5000] ^= 1
	mustWrite(t, other, img)
	dir := t.TempDir()
	patched := filepath.Join(dir, "patched.md")
	if code, _, stderr := exec("inject", "--base", base, "--elf", pocELF, "--out", patched, "--size", "0x200000"); code != 0 {
		t.Fatalf("inject: code %d stderr %q", code, stderr)
	}
	patch := filepath.Join(dir, "patch.bps")
	if code, _, stderr := exec("bps", "create", "--base", base, "--target", patched, "--out", patch); code != 0 {
		t.Fatalf("bps create: code %d stderr %q", code, stderr)
	}
	code, _, stderr := exec("bps", "apply", "--base", other, "--patch", patch, "--out", filepath.Join(dir, "x.md"))
	if code != 1 || !strings.Contains(stderr, "source checksum") {
		t.Fatalf("code %d stderr %q", code, stderr)
	}
}

